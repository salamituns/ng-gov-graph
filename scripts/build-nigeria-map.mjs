// Builds src/data/nigeria/map-shapes.ts: Nigeria's 36 states and the FCT as small SVG paths for the hub.
// Source: geoBoundaries NGA ADM1 (GRID3, 2022), CC BY 4.0. Run: node scripts/build-nigeria-map.mjs
import { writeFileSync } from 'node:fs'

const SOURCE =
	'https://github.com/wmgeolab/geoBoundaries/raw/9469f09/releaseData/gbOpen/NGA/ADM1/geoBoundaries-NGA-ADM1_simplified.geojson'
const WIDTH = 120 // drawing box in map units; the hub scales it
const TOLERANCE = 0.9 // Douglas–Peucker tolerance in drawing units

const geo = await (await fetch(SOURCE)).json()

// Equirectangular with cos(latitude) scaling is accurate enough across Nigeria's 4°–14° N.
const midLat = 9
const project = ([lon, lat]) => [lon * Math.cos((midLat * Math.PI) / 180), -lat]
const rings = geo.features.flatMap((feature) => {
	const polys = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates
	return polys.map((poly) => ({ name: feature.properties.shapeName, ring: poly[0].map(project) }))
})
const xs = rings.flatMap((r) => r.ring.map((p) => p[0]))
const ys = rings.flatMap((r) => r.ring.map((p) => p[1]))
const [minX, maxX, minY, maxY] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)]
const scale = WIDTH / (maxX - minX)
const height = (maxY - minY) * scale
const toBox = ([x, y]) => [(x - minX) * scale - WIDTH / 2, (y - minY) * scale - height / 2]

function simplify(points, tolerance) {
	if (points.length < 4) return points
	const [a, b] = [points[0], points.at(-1)]
	let index = 0
	let max = 0
	for (let i = 1; i < points.length - 1; i++) {
		const [px, py] = points[i]
		const dx = b[0] - a[0]
		const dy = b[1] - a[1]
		const distance = Math.abs(dy * px - dx * py + b[0] * a[1] - b[1] * a[0]) / (Math.hypot(dx, dy) || 1)
		if (distance > max) [max, index] = [distance, i]
	}
	if (max <= tolerance) return [a, b]
	return [...simplify(points.slice(0, index + 1), tolerance).slice(0, -1), ...simplify(points.slice(index), tolerance)]
}

const slug = (name) =>
	name.toLowerCase().replace(/\s+state$/, '').replace(/federal capital territory/, 'fct').replace(/[^a-z]+/g, '-').replace(/^-|-$/g, '')
const idFor = (name) => {
	const s = slug(name)
	if (/(^|-)fct$/.test(s) || s.includes('abuja')) return 'ng-fct'
	return `ng-${s === 'nassarawa' ? 'nasarawa' : s}-state`
}

// A closed ring starts and ends on the same point, so simplify it as two halves split at its far point.
function simplifyRing(ring, tolerance) {
	let far = 0
	let best = -1
	for (let i = 1; i < ring.length; i++) {
		const distance = Math.hypot(ring[i][0] - ring[0][0], ring[i][1] - ring[0][1])
		if (distance > best) [best, far] = [distance, i]
	}
	return [...simplify(ring.slice(0, far + 1), tolerance).slice(0, -1), ...simplify(ring.slice(far), tolerance)]
}

const byState = new Map()
for (const { name, ring } of rings) {
	const points = simplifyRing(ring.map(toBox), TOLERANCE)
	if (points.length < 3) continue
	const d = `M${points.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L')}Z`
	byState.set(idFor(name), (byState.get(idFor(name)) ?? '') + d)
}

// Abuja, the capital: 9.06° N, 7.49° E.
const [ax, ay] = toBox(project([7.4951, 9.0579]))
const out = `// Generated by scripts/build-nigeria-map.mjs. Do not edit by hand.
// Boundaries: geoBoundaries NGA ADM1 (GRID3, 2022), licensed CC BY 4.0. https://www.geoboundaries.org
export const NIGERIA_MAP = {
	width: ${WIDTH},
	height: ${height.toFixed(1)},
	abuja: { x: ${ax.toFixed(1)}, y: ${ay.toFixed(1)} },
	attribution: 'State boundaries: geoBoundaries (GRID3, 2022), CC BY 4.0',
	states: ${JSON.stringify(Object.fromEntries([...byState].sort()), null, 2).replace(/\n/g, '\n\t')} as Record<string, string>,
}
`
writeFileSync(new URL('../src/data/nigeria/map-shapes.ts', import.meta.url), out)
console.log(`wrote ${byState.size} states, ${out.length} bytes, box ${WIDTH}×${height.toFixed(1)}`)
